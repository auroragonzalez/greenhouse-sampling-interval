"""Write a SYNTHETIC stand-in for the Osiris campaign data to ``data/``.

The real measurements of the August and September 2026 campaigns are being
prepared for publication on Zenodo and are not in this repository yet. This
script fills ``data/`` with files that have the same names, columns, time
conventions and coverage as the real exports, so that every script in
``scripts/`` runs end to end. **The numbers are random and come from a toy
plant; results computed from them do not reproduce the paper.**

What is generated
-----------------
* A commanded schedule that follows the protocol encoded in
  ``src/protocol_check.py``: Phase A step trials (days 1-5), Phase B
  dose-response, Phase C fractional factorial and Phase D random blocks
  (2 h treatment + 1 h washout to zero, 3 Aug - 2 Sep), then a September
  campaign of 30 min holds each followed by a 30 min washout
  (16 Sep 14:00 - 23 Sep 07:00).
* Exterior weather with a diurnal cycle and day-to-day noise.
* Interior temperature and humidity from a first-order plant (tau = 16 min)
  driven by the weather and the executed actuator levels, including the 45 C
  safety interlock (windows 100 %, shade and lights off).

Layout written (the same one ``protocol_check`` reads)::

    data/raw/*.csv                         interior sensors and actuators
    data/raw/outside data/*.csv            on-site weather station
    data/raw/forecast data/hourly_weather_data.csv
    data/openmeteo/openmeteo_*.csv         Open-Meteo archive and forecasts
    data/blocks/august_blocks.csv          commanded level per August block

Usage::

    python3 tools/make_synthetic_data.py [--seed 0] [--out data]
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import protocol_check as pc  # noqa: E402

GROUPS = list(pc.GROUPS)            # LIGHTS FOG VENT_ROOF VENT_SIDE SHADE RECIRC RECIRC2
UTC = pc.UTC_OFFSET

EXT_START, EXT_END = pd.Timestamp("2026-08-01 00:00"), pd.Timestamp("2026-09-23 23:59")
INT_START, INT_END = pd.Timestamp("2026-08-03 00:00"), pd.Timestamp("2026-09-23 06:59")
SEPT_START = pd.Timestamp("2026-09-16 14:00")
TAU_MIN = 16.0

NOTICE = ("# SYNTHETIC DATA generated by tools/make_synthetic_data.py - "
          "not measurements; the real data will be published on Zenodo.\n")


# --------------------------------------------------------------------------- #
# Schedule
# --------------------------------------------------------------------------- #

def _block(cmd: pd.DataFrame, t0: pd.Timestamp, levels: dict, hold: pd.Timedelta):
    cmd.loc[t0:t0 + hold - pd.Timedelta("1min"), list(levels)] = list(levels.values())


def schedule(rng: np.random.Generator) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Commanded level per minute, and one row per August 3-h block."""
    idx = pd.date_range(INT_START, INT_END, freq="1min")
    cmd = pd.DataFrame(0.0, index=idx, columns=GROUPS)
    treat = pd.Timedelta(hours=pc.TREATMENT_HOURS)

    for tr in pc.PHASE_A:
        if tr["group"] is None:
            continue
        t0 = pc.DAY1 + pd.Timedelta(days=tr["day"] - 1, hours=tr["hour"])
        _block(cmd, t0, {tr["group"]: tr["level"]}, treat)

    def day0(d):
        return pc.DAY1 + pd.Timedelta(days=d - 1)

    def starts(phase):
        a, b = pc.PHASES[phase]
        return pd.date_range(day0(a), day0(b + 1), freq=f"{pc.BLOCK_HOURS}h", inclusive="left")

    designs: dict[pd.Timestamp, list[float]] = {}
    seq_b = [(g, lv) for g, lvls in pc.PHASE_B for lv in lvls]
    for t0, (g, lv) in zip(starts("B"), seq_b):
        designs[t0] = [lv if c == g else 0.0 for c in GROUPS]
    runs_c = list(pc.PHASE_C) + [pc.PHASE_C[i] for i in rng.permutation(len(pc.PHASE_C))]
    for t0, run in zip(starts("C"), runs_c):
        designs[t0] = run
    for k, t0 in enumerate(starts("D")):
        designs[t0] = (pc.PHASE_D_SAMPLE[k] if k < len(pc.PHASE_D_SAMPLE)
                       else [float(rng.choice(pc.GROUPS[g].levels)) for g in GROUPS])
    for t0, run in designs.items():
        _block(cmd, t0, dict(zip(GROUPS, map(float, run))), treat)

    # September: 30 min hold, 30 min washout to zero.
    for t0 in pd.date_range(SEPT_START, INT_END, freq="1h"):
        _block(cmd, t0, {g: float(rng.choice(pc.GROUPS[g].levels)) for g in GROUPS},
               pd.Timedelta("30min"))

    rows = []
    for i, t0 in enumerate(pd.date_range(pc.DAY1, day0(32), freq=f"{pc.BLOCK_HOURS}h",
                                         inclusive="left")):
        r = dict(block_id=f"AUG{i + 1:03d}", start_local=t0, phase=pc.phase_of(t0),
                 campaign_day=pc.campaign_day(t0))
        for g, v in zip(GROUPS, designs.get(t0, [np.nan] * len(GROUPS))):
            r[f"cmd_{g}"] = v
        rows.append(r)
    return cmd, pd.DataFrame(rows)


# --------------------------------------------------------------------------- #
# Weather
# --------------------------------------------------------------------------- #

def weather(rng: np.random.Generator) -> pd.DataFrame:
    """Exterior temperature, humidity, PAR (W m-2) and wind (m/s) per minute, local time."""
    idx = pd.date_range(EXT_START, EXT_END, freq="1min")
    hour = idx.hour + idx.minute / 60.0
    day = (idx.normalize() - EXT_START).days.values
    nd = day.max() + 1
    season = np.linspace(0, 1, nd)
    t_mean = (28.5 - 4.0 * season + rng.normal(0, 1.2, nd))[day]
    t_amp = (6.5 + rng.normal(0, 0.8, nd))[day]
    cloud = np.clip(1 - rng.gamma(0.6, 0.12, nd), 0.35, 1.0)[day]
    daylen = (13.8 - 1.8 * season)[day]

    def ar1(n, phi, sd):
        e = rng.normal(0, sd, n)
        out = np.empty(n)
        out[0] = e[0]
        for i in range(1, n):
            out[i] = phi * out[i - 1] + e[i]
        return out

    n = len(idx)
    temp = t_mean + t_amp * np.cos(2 * np.pi * (hour - 15.5) / 24) + ar1(n, 0.995, 0.05)
    hum = np.clip(62 - 3.0 * (temp - t_mean) + ar1(n, 0.995, 0.25), 12, 98)
    sun = np.clip(np.cos(np.pi * (hour - 14.2) / daylen), 0, None)
    par = 470 * sun ** 1.3 * cloud * np.clip(1 + ar1(n, 0.98, 0.01), 0.6, 1.2)
    wind = np.clip(1.2 + 1.8 * sun + ar1(n, 0.97, 0.12), 0, None)
    return pd.DataFrame(dict(temp=temp, hum=hum, par=par, wind=wind), index=idx)


# --------------------------------------------------------------------------- #
# Plant
# --------------------------------------------------------------------------- #

def simulate(cmd: pd.DataFrame, wx: pd.DataFrame, rng: np.random.Generator):
    """First-order plant per minute; returns interior states and executed levels."""
    w = wx.reindex(cmd.index)
    Te, He, Pe, We = (w[c].values for c in ("temp", "hum", "par", "wind"))
    C = cmd.values
    n = len(cmd)
    ex = C.copy()
    T = np.empty(n); H = np.empty(n)
    T[0], H[0] = Te[0] + 0.5, He[0]
    gi = {g: i for i, g in enumerate(GROUPS)}
    hot = False
    noise_t = rng.normal(0, 0.04, n)
    noise_h = rng.normal(0, 0.15, n)
    for k in range(n):
        t_prev = T[k - 1] if k else T[0]
        h_prev = H[k - 1] if k else H[0]
        if t_prev > pc.SAFETY["overtemp_c"]:
            hot = True
        elif t_prev < pc.SAFETY["overtemp_c"] - 2:
            hot = False
        if hot:
            ex[k, gi["VENT_ROOF"]] = ex[k, gi["VENT_SIDE"]] = 100.0
            ex[k, gi["SHADE"]] = ex[k, gi["LIGHTS"]] = 0.0
        r, s, sh = ex[k, gi["VENT_ROOF"]] / 100, ex[k, gi["VENT_SIDE"]] / 100, ex[k, gi["SHADE"]] / 100
        f, li = ex[k, gi["FOG"]] / 20, ex[k, gi["LIGHTS"]] / 10
        rc, rc2 = ex[k, gi["RECIRC"]], ex[k, gi["RECIRC2"]]
        gain = 0.030 * Pe[k] * (1 - 0.55 * sh) + 0.8 * li + 0.4 * rc2 + 0.1 * rc
        cond = 1 + 2.2 * r + 1.8 * s + 0.25 * We[k] * (r + s)
        evap = 4.5 * f * (1 - h_prev / 100)
        t_eq = Te[k] + gain / cond - evap
        h_eq = He[k] * np.exp(-0.055 * (t_prev - Te[k])) + 30 * f * (1 - h_prev / 100) / cond
        T[k] = t_prev + (t_eq - t_prev) / TAU_MIN + noise_t[k]
        H[k] = float(np.clip(h_prev + (h_eq - h_prev) / 12.0 + noise_h[k], 5, 100))
    executed = pd.DataFrame(ex, index=cmd.index, columns=GROUPS)
    sh = executed["SHADE"].values / 100
    svp = 0.6108 * np.exp(17.27 * T / (T + 237.3))
    sens = pd.DataFrame({
        "temp_centro": T,
        "temp_alta": T + 0.7 + 0.004 * Pe * (1 - sh) + rng.normal(0, 0.05, n),
        "temp_baja": T - 0.5 + rng.normal(0, 0.05, n),
        "hum_centro": H,
        "hum_alta": np.clip(H - 2.5 + rng.normal(0, 0.3, n), 5, 100),
        "hum_baja": np.clip(H + 2.0 + rng.normal(0, 0.3, n), 5, 100),
        "co2": 420 + 15 * np.sin(2 * np.pi * np.arange(n) / 1440) + rng.normal(0, 6, n),
        "dpv": svp * (1 - H / 100),
        "par": np.clip(1.4 * Pe * (1 - 0.6 * sh) + 25 * executed["LIGHTS"].values
                       + rng.normal(0, 2, n), 0, None),
        "rad": np.clip(0.9 * Pe * (1 - 0.6 * sh) + rng.normal(0, 2, n), 0, None),
    }, index=cmd.index)
    return sens, executed


# --------------------------------------------------------------------------- #
# Writers
# --------------------------------------------------------------------------- #

def _utc(idx: pd.DatetimeIndex) -> np.ndarray:
    return (idx - UTC).strftime("%Y-%m-%dT%H:%M:%SZ").values


def write_events(path: pathlib.Path, s: pd.Series, decimals: int = 2):
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({"_time": _utc(s.index), "_value": s.round(decimals).values}).to_csv(path, index=False)


def write_changes(path: pathlib.Path, s: pd.Series):
    """Actuator log: one record per change of level, plus first and last minute."""
    keep = s.ne(s.shift())
    keep.iloc[-1] = True
    write_events(path, s[keep], 1)


def write_fog(path: pathlib.Path, duty: pd.Series):
    """Fog valve log: 1 at the start of a sprayed minute, 0 after ``duty`` seconds."""
    t, v = [duty.index[0]], [0]
    on = duty[duty > 0]
    for t0, sec in on.items():
        t += [t0, t0 + pd.Timedelta(seconds=float(sec))]
        v += [1, 0]
    t.append(duty.index[-1]); v.append(0)
    idx = pd.DatetimeIndex(t)
    pd.DataFrame({"_time": _utc(idx), "_value": v}).to_csv(path, index=False)


def main(seed: int, out: pathlib.Path):
    rng = np.random.default_rng(seed)
    raw = out / "raw"
    (raw / "outside data").mkdir(parents=True, exist_ok=True)
    (raw / "forecast data").mkdir(parents=True, exist_ok=True)
    (out / "openmeteo").mkdir(parents=True, exist_ok=True)
    (out / "blocks").mkdir(parents=True, exist_ok=True)

    print("schedule ...", flush=True)
    cmd, blocks = schedule(rng)
    print("weather ...", flush=True)
    wx = weather(rng)
    print("plant ...", flush=True)
    sens, ex = simulate(cmd, wx, rng)

    print("writing interior sensors and actuators ...", flush=True)
    for name, f in pc.SENSORS.items():
        write_events(raw / f, sens[name])
    for g in pc.GROUPS.values():
        if g.name == "FOG":
            write_fog(raw / g.files[0], ex["FOG"])
            continue
        for f in g.files:
            write_changes(raw / f, ex[g.name])

    print("writing weather station ...", flush=True)
    st = wx.copy()
    five = st.iloc[::5]
    for stem, col in (("Temperatura_ambiente", "temp"), ("Humedad_ambiente", "hum"),
                      ("Radiacion_solar_par", "par")):
        write_events(raw / "outside data" / f"{stem}.csv", five[col])
    write_events(raw / "outside data" / "Velocidad_del_viento.csv", st["wind"])
    write_events(raw / "outside data" / "Radiación_solar_global_0.csv",
                 pd.Series(-999999.0, index=five.index))      # dead channel, as in the real export
    rain_t = pd.date_range("2026-09-01 12:00", "2026-09-01 13:30", freq="10min")
    write_events(raw / "outside data" / pc.RAIN_FILE, pd.Series(0.2, index=rain_t))

    print("writing forecasts ...", flush=True)
    hourly = wx.resample("1h").mean()
    nh = len(hourly)

    def jitter(sd_t, sd_h, sd_w, sd_r):
        return pd.DataFrame({
            "temp": hourly.temp + rng.normal(0, sd_t, nh),
            "hum": np.clip(hourly.hum + rng.normal(0, sd_h, nh), 0, 100),
            "wind": np.clip(hourly.wind + rng.normal(0, sd_w, nh), 0, None),
            "sw": np.clip(hourly.par / 0.5 * (1 + rng.normal(0, sd_r, nh)), 0, None)
                  * (hourly.par > 0),
        }, index=hourly.index)

    # Accumulated channels are labelled at the end of their hour (protocol_check fact 5).
    def label_end(df):
        d = df.copy()
        d["sw"] = d["sw"].shift(1).fillna(0.0)
        return d

    an, pr = label_end(jitter(0.6, 4, 0.4, 0.05)), label_end(jitter(1.0, 6, 0.6, 0.12))
    fc = pd.DataFrame({
        "date": hourly.index.strftime("%Y-%m-%d %H:%M:%S"),
        "temperature_2m": an.temp.round(2).values, "temperature_2m_previous_day1": pr.temp.round(2).values,
        "relative_humidity_2m": an.hum.round(2).values, "relative_humidity_2m_previous_day1": pr.hum.round(2).values,
        "precipitation": 0.0, "precipitation_previous_day1": 0.0,
        "wind_speed_10m": an.wind.round(2).values, "wind_speed_10m_previous_day1": pr.wind.round(2).values,
        "shortwave_radiation": an.sw.round(1).values, "shortwave_radiation_previous_day1": pr.sw.round(1).values,
    })
    fc.to_csv(raw / "forecast data" / "hourly_weather_data.csv", index=False)

    # Open-Meteo wind is km/h at 10 m; the station sees ~0.3 + 0.64 x it (in m/s).
    def om_wind(df):
        return np.clip((df.wind - 0.302) / 0.642, 0, None) * 3.6

    tag = "2026-08-01_2026-09-23"
    t_iso = hourly.index.strftime("%Y-%m-%dT%H:%M")
    arch = label_end(jitter(0.5, 3, 0.3, 0.04))
    pd.DataFrame({"time": t_iso, "temperature_2m": arch.temp.round(1).values,
                  "relative_humidity_2m": arch.hum.round().values,
                  "wind_speed_10m": om_wind(arch).round(1).values,
                  "shortwave_radiation": arch.sw.round(1).values}
                 ).to_csv(out / "openmeteo" / f"openmeteo_archive_{tag}.csv", index=False)
    head = ("latitude,longitude,elevation,utc_offset_seconds,timezone,timezone_abbreviation\n"
            "37.99,-1.16,92.0,7200,Europe/Madrid,GMT+2\n\n")
    for name, sfx, df in (("histforecast", "", an), ("dayahead", "_previous_day1", pr)):
        body = pd.DataFrame({
            "time": t_iso,
            f"temperature_2m{sfx} (°C)": df.temp.round(1).values,
            f"relative_humidity_2m{sfx} (%)": df.hum.round().values,
            f"wind_speed_10m{sfx} (km/h)": om_wind(df).round(1).values,
            f"shortwave_radiation{sfx} (W/m²)": df.sw.round(1).values,
        }).to_csv(index=False)
        (out / "openmeteo" / f"openmeteo_{name}_{tag}.csv").write_text(head + body, encoding="utf-8")

    print("writing block table ...", flush=True)
    for g in GROUPS:
        blocks[f"exec_{g}"] = [ex[g].loc[t0 + pc.RAMP_SKIP:t0 + pd.Timedelta(hours=2)].mode().iloc[0]
                               for t0 in blocks.start_local]
    seg = [sens.loc[t0:t0 + pd.Timedelta(hours=2) - pd.Timedelta("1min")] for t0 in blocks.start_local]
    blocks["t_centre_mean"] = [s.temp_centro.mean().round(2) for s in seg]
    blocks["t_centre_max"] = [s.temp_centro.max().round(2) for s in seg]
    blocks["rh_centre_mean"] = [s.hum_centro.mean().round(2) for s in seg]
    blocks["overtemp_minutes"] = [int((s.temp_centro > pc.SAFETY["overtemp_c"]).sum()) for s in seg]
    blocks.to_csv(out / "blocks" / "august_blocks.csv", index=False)

    (out / "SYNTHETIC_DATA_README.txt").write_text(NOTICE.lstrip("# ") + (
        f"seed = {seed}; interior {INT_START} - {INT_END} local; "
        f"interlock active {int((ex.VENT_ROOF.values != cmd.VENT_ROOF.values).sum())} min.\n"))
    print(f"done -> {out}  (T_int {sens.temp_centro.min():.1f}..{sens.temp_centro.max():.1f} C)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", type=pathlib.Path, default=ROOT / "data")
    a = ap.parse_args()
    main(a.seed, a.out)
